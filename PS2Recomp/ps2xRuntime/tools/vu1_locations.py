#!/usr/bin/env python3
"""Write vu1_locations.toml: where the code of every compiled VU1 program (src/lib/vu/vu1gen/) lies in
the game's executable, so players' builds generate the same programs from their own disc (ps2xVuGen).
The file holds start pcs, signatures and file offsets only, no instruction words.

Usage: vu1_locations.py [vu1gen dir] [SLES_537.18] [out.toml]
Defaults: src/lib/vu/vu1gen, extracted/SLES_537.18 and vu1_locations.toml in the project root.
"""
import re
import struct
import sys
from pathlib import Path

RUNTIME = Path(__file__).resolve().parents[1]
ROOT = RUNTIME.parents[1]
HEADER_RX = re.compile(r"^// Generated by ps2EntryRunner --vu-gen from (.+)\. Do not edit; regenerate instead\.\n"
                       r"// VU1 program at pc 0x([0-9a-f]+): (\d+) reachable instruction pairs \((\d+) compiled\), signature ([0-9a-f]{16})\.")
PAIR_RX = re.compile(r"VU1_COMPILED_PAIR(?:_S)?\((\d+), 0x([0-9a-f]{8})u, 0x([0-9a-f]{8})u")


def load_programs(gen):
    programs = []
    for f in sorted(gen.glob("vu1p_" + "?" * 16 + ".cpp")):
        m = HEADER_RX.match(f.read_text())
        if not m:
            sys.exit(f"{f.name}: unexpected header")
        source, pc, reachable, compiled, signature = m[1], int(m[2], 16), int(m[3]), int(m[4]), m[5]
        if reachable != compiled:
            sys.exit(f"{f.name}: {reachable - compiled} reachable pairs were not compiled; their words cannot be located")
        pairs = {}
        for chunk in sorted(gen.glob(f"vu1p_{signature}_*.cpp")):
            for p in PAIR_RX.finditer(chunk.read_text()):
                pairs[int(p[1])] = struct.pack("<II", int(p[2], 16), int(p[3], 16))
        if len(pairs) != compiled:
            sys.exit(f"{f.name}: {len(pairs)} pairs in its chunk files, {compiled} expected")
        programs.append((signature, pc, source, pairs))
    return programs


def locate(pairs, elf, name):
    """[first pair, count, offset]: runs of consecutive pairs, each as long as it is found in one piece."""
    out = []
    indices = sorted(pairs)
    k = 0
    while k < len(indices):
        blob, offset, j = b"", -1, k
        while j < len(indices) and (j == k or indices[j] == indices[j - 1] + 1):
            found = elf.find(blob + pairs[indices[j]])
            if found < 0:
                break
            blob, offset, j = blob + pairs[indices[j]], found, j + 1
        if j == k:
            sys.exit(f"{name}: pair {indices[k]} not found in the executable")
        out.append((indices[k], j - k, offset))
        k = j
    return out


def main():
    args = sys.argv[1:]
    gen = Path(args[0]) if len(args) > 0 else RUNTIME / "src" / "lib" / "vu" / "vu1gen"
    elf_path = Path(args[1]) if len(args) > 1 else ROOT / "extracted" / "SLES_537.18"
    out_path = Path(args[2]) if len(args) > 2 else ROOT / "vu1_locations.toml"
    elf = elf_path.read_bytes()
    programs = load_programs(gen)
    sources = {p[2] for p in programs}
    common = sources.pop() if len(sources) == 1 else None
    lines = [
        "# The VU1 programs compiled into ps2xRuntime/src/lib/vu/vu1gen/ and where their code lies in the",
        "# game's executable: ps2xVuGen reads it from the player's own files and writes the same programs.",
        "# Written by ps2xRuntime/tools/vu1_locations.py; holds no instruction words.",
        f'file = "{elf_path.name}"',
    ]
    if common:
        lines.append(f'source = "{common}" # the recording the programs came from (named in the generated files)')
    for signature, pc, source, pairs in programs:
        code = ", ".join(f"[{first}, {count}, 0x{offset:x}]" for first, count, offset in locate(pairs, elf, signature))
        lines += ["", "[[program]]", f"signature = 0x{signature}", f"start_pc = 0x{pc:04x}"]
        if not common:
            lines.append(f'source = "{source}"')
        lines.append(f"code = [{code}] # [first pair, pair count, file offset]")
    out_path.write_text("\n".join(lines) + "\n")
    print(f"{out_path}: {len(programs)} programs")


if __name__ == "__main__":
    main()
